"""Write `requirements.lock` — the pinned Linux/CPU closure of `requirements.txt`.

The owner's venv has no pip (`venv/bin/python -m pip` → "No module named pip"),
so `pip freeze` is not available here and never will be. This walks the
installed distributions instead: every name in `requirements.txt` is resolved
through `importlib.metadata.requires()`, extras are followed
(`discord.py[voice]`, `uvicorn[standard]`, `python-jose[cryptography]`),
environment markers are evaluated for THIS interpreter, and every distribution
the walk reaches is pinned `name==version`.

Two deliberate departures from a raw freeze:

  * `nvidia-*`, `cuda-*` and `triton` are dropped. They are torch's CUDA extras —
    pulled
    in because this machine has a GPU. CI and the Dockerfile install torch from
    the CPU index, where those wheels do not exist, and a lock naming them
    would be uninstallable there.
  * `torch` is pinned by version only. The installed build is a CUDA one
    (`+cu130` local version); the version alone resolves on both indexes.

Run:  venv/bin/python scripts/write_lock.py [--check]

`--check` re-generates and diffs instead of writing, so CI or a reviewer can
prove the lock still matches the tree.
"""
from __future__ import annotations

import argparse
import importlib.metadata as metadata
import re
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Set, Tuple

from packaging.markers import Marker
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

REPO = Path(__file__).resolve().parents[1]
REQUIREMENTS = REPO / "requirements.txt"
LOCKFILE = REPO / "requirements.lock"

# torch's CUDA extras. Present here because the generating box has a GPU; absent
# from the CPU index CI and the Dockerfile install from. `cuda-toolkit`,
# `cuda-bindings` and `cuda-pathfinder` are the same thing under a different
# prefix — torch declares all of them under `platform_system == "Linux"`.
EXCLUDED_PREFIXES = ("nvidia-", "cuda-")
EXCLUDED_NAMES = {"triton"}

# Pinned by version only — the installed wheel carries a local version
# (`+cu130`) that exists on exactly one index.
VERSION_ONLY = {"torch"}

HEADER = """\
# requirements.lock — the pinned Linux/CPU closure of requirements.txt.
#
# Generated by `venv/bin/python scripts/write_lock.py` from the
# installed distributions (importlib.metadata, not `pip freeze` — the venv this
# was generated in has no pip). Every name in requirements.txt was walked
# through its own declared requirements, extras followed, environment markers
# evaluated for CPython 3.13 on Linux.
#
# torch is pinned by VERSION ONLY and the `nvidia-*`, `cuda-*` and `triton` wheels
# are left out on purpose: they are torch's CUDA extras, and the CPU wheel does not
# want them. Install torch FIRST from the CPU index, then this file:
#
#     pip install torch==%(torch)s --index-url https://download.pytorch.org/whl/cpu
#     pip install -r requirements.lock
#
# That is exactly what .github/workflows/gate.yml and the Dockerfile do. On a
# machine with a GPU, install torch from your CUDA index instead and the rest of
# this file is unchanged.
#
# Optional extras (voice: faster-whisper, pyttsx3) are NOT locked here — they
# are declared in pyproject.toml and are not installed in the generating venv.
#
# Regenerate:  venv/bin/python scripts/write_lock.py
# Verify:      venv/bin/python scripts/write_lock.py --check
"""


def parse_requirements(text: str) -> List[Requirement]:
    """Every non-comment, non-blank line of requirements.txt as a Requirement."""
    out: List[Requirement] = []
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        out.append(Requirement(line))
    return out


def _is_excluded(name: str) -> bool:
    canonical = canonicalize_name(name)
    return canonical in EXCLUDED_NAMES or canonical.startswith(EXCLUDED_PREFIXES)


def _marker_holds(marker: Optional[Marker], extra: Optional[str]) -> bool:
    if marker is None:
        return True
    # An extra-guarded requirement is reachable only while walking that extra.
    environment = {"extra": extra or ""}
    try:
        return bool(marker.evaluate(environment))
    except Exception:
        return False


def closure(roots: Iterable[Requirement]) -> Tuple[Dict[str, str], List[str]]:
    """Walk the installed metadata. Returns {canonical name: version}, missing."""
    versions: Dict[str, str] = {}
    missing: List[str] = []
    seen: Set[Tuple[str, str]] = set()
    queue: List[Tuple[str, Tuple[str, ...]]] = [
        (req.name, tuple(sorted(req.extras))) for req in roots
    ]

    while queue:
        name, extras = queue.pop()
        canonical = canonicalize_name(name)
        key = (canonical, ",".join(extras))
        if key in seen or _is_excluded(canonical):
            continue
        seen.add(key)
        try:
            distribution = metadata.distribution(name)
        except metadata.PackageNotFoundError:
            if canonical not in missing:
                missing.append(canonical)
            continue
        versions[canonical] = str(distribution.version)
        for raw in distribution.requires or []:
            try:
                child = Requirement(raw)
            except Exception:
                continue
            if _is_excluded(child.name):
                continue
            # Plain dependency, or one guarded by an extra we asked for.
            if _marker_holds(child.marker, None):
                queue.append((child.name, tuple(sorted(child.extras))))
                continue
            for extra in extras:
                if _marker_holds(child.marker, extra):
                    queue.append((child.name, tuple(sorted(child.extras))))
                    break
    return versions, missing


def render(roots: List[Requirement], versions: Dict[str, str]) -> str:
    """The lock body: one `name==version` per distribution, markers preserved."""
    # A marker that a stranger's requirements.txt carries (opencv's
    # `sys_platform != "darwin"`) has to survive into the lock, or installing it
    # on a Mac breaks on a wheel that was never meant to be there.
    markers: Dict[str, str] = {}
    for req in roots:
        if req.marker is not None:
            markers[canonicalize_name(req.name)] = str(req.marker)

    torch_version = versions.get("torch", "2.12.0")
    lines = [HEADER % {"torch": torch_version}]
    for canonical in sorted(versions):
        version = versions[canonical]
        if canonical in VERSION_ONLY:
            version = version.split("+", 1)[0]
        pin = f"{canonical}=={version}"
        marker = markers.get(canonical)
        if marker:
            pin = f"{pin}; {marker}"
        lines.append(pin)
    return "\n".join(lines) + "\n"


def build() -> Tuple[str, List[str]]:
    roots = parse_requirements(REQUIREMENTS.read_text(encoding="utf-8"))
    versions, missing = closure(roots)
    return render(roots, versions), missing


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write — exit 1 if requirements.lock is out of date.",
    )
    args = parser.parse_args(argv)

    body, missing = build()
    for name in missing:
        print(f"warning: {name} is named in the closure but not installed here", file=sys.stderr)

    if args.check:
        current = LOCKFILE.read_text(encoding="utf-8") if LOCKFILE.exists() else ""
        if current == body:
            print("requirements.lock is current.")
            return 0
        print("requirements.lock is out of date — rerun without --check.", file=sys.stderr)
        return 1

    LOCKFILE.write_text(body, encoding="utf-8")
    pins = len([l for l in body.splitlines() if l and not l.startswith("#")])
    print(f"Wrote {LOCKFILE.relative_to(REPO)} — {pins} pins.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
