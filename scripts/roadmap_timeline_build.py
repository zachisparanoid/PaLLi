#!/usr/bin/env python3
"""Regenerate the roadmap time-travel states file.

Walks the git history of docs/roadmap/palli-roadmap.html (the LIVING page,
owner-set 2026-07-26: updated as steps complete) and writes every committed
version — oldest first, working copy last if it differs — into
docs/roadmap/roadmap_states.js for roadmap-timeline.html's Previous/Next
viewer.

Part of the wrap ritual (owner-requested 2026-07-28): after each
implementation updates the living page, re-run this so the timeline gains
the new frame:

    venv/bin/python scripts/roadmap_timeline_build.py
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
PAGE = "docs/roadmap/palli-roadmap.html"
OUT = REPO / "docs/roadmap/roadmap_states.js"


def _git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=REPO, check=True, capture_output=True, text=True
    ).stdout


def main() -> None:
    # NOTE: no --follow — it does not compose with --reverse (git's --follow
    # is a single-path hack that truncates the reversed walk), and this file
    # has never moved. If it ever moves, walk forward without --reverse and
    # reverse in Python instead.
    log = _git(
        "log", "--reverse", "--format=%H%x1f%ci%x1f%s", "--", PAGE
    ).strip()
    states = []
    for line in log.splitlines():
        sha, date, subject = line.split("\x1f", 2)
        html = _git("show", f"{sha}:{PAGE}")
        states.append(
            {"sha": sha[:7], "date": date[:16], "subject": subject, "html": html}
        )
    working = (REPO / PAGE).read_text(encoding="utf-8")
    if not states or states[-1]["html"] != working:
        states.append(
            {"sha": "working", "date": "now", "subject": "uncommitted working copy",
             "html": working}
        )
    OUT.write_text(
        "// GENERATED by scripts/roadmap_timeline_build.py — do not hand-edit.\n"
        "// One frame per committed version of the living roadmap page.\n"
        f"window.ROADMAP_STATES = {json.dumps(states, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(REPO)}: {len(states)} states "
          f"({states[0]['date']} .. {states[-1]['date']})")


if __name__ == "__main__":
    sys.exit(main())
