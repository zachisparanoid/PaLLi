def _sqlite_sidecars(db_path: Path) -> list[Path]:
    return [
        db_path.with_name(f"{db_path.name}-wal"),
        db_path.with_name(f"{db_path.name}-shm"),
        db_path.with_name(f"{db_path.name}-journal"),
    ]


class _FakePragmaCursor:
    def __init__(self, row):
        self._row = row
        self.closed = False

    async def fetchone(self):
        return self._row

    async def close(self):
        self.closed = True


class _FakePragmaConnection:
    def __init__(
        self,
        *,
        wal_row=("wal",),
        wal_error: Exception | None = None,
        delete_row=("delete",),
        delete_error: Exception | None = None,
    ) -> None:
        self.wal_row = wal_row
        self.wal_error = wal_error
        self.delete_row = delete_row
        self.delete_error = delete_error
        self.calls: list[str] = []

    async def execute(self, query: str):
        self.calls.append(query)
        if query == "PRAGMA journal_mode=WAL":
            if self.wal_error is not None:
                raise self.wal_error
            return _FakePragmaCursor(self.wal_row)
        if query == "PRAGMA journal_mode=DELETE":
            if self.delete_error is not None:
                raise self.delete_error
            return _FakePragmaCursor(self.delete_row)
        return _FakePragmaCursor((None,))

    async def commit(self):
        self.calls.append("COMMIT")


