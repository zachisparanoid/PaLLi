@pytest.mark.asyncio
async def test_configure_sqlite_connection_falls_back_when_wal_unavailable() -> None:
    raw = _FakePragmaConnection(
        wal_error=sqlite3.OperationalError("unable to open database file"),
    )

    await configure_sqlite_connection(raw)

    assert raw.calls == [
        "PRAGMA journal_mode=WAL",
        "PRAGMA journal_mode=DELETE",
        "PRAGMA foreign_keys=ON",
        "PRAGMA busy_timeout=15000",
        "COMMIT",
    ]


