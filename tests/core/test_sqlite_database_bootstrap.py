def test_inspect_sqlite_database_path_reports_journal_fallback(monkeypatch, tmp_path: Path) -> None:
    target = tmp_path / "data" / "palli-local.sqlite3"
    target.parent.mkdir(parents=True, exist_ok=True)

    monkeypatch.setattr(
        "core.sqlite_database_bootstrap._configure_sqlite_journal_mode_sync",
        lambda raw, log_warnings=True: {"effective_mode": "delete", "fallback_active": True},
    )

    details = inspect_sqlite_database_path(target)

    assert details["writable"] is True
    assert details["openable"] is True
    assert details["journal_mode_effective"] == "delete"
    assert details["journal_mode_fallback_active"] is True
    assert "DELETE journal mode" in details["journal_mode_warning"]


@pytest.mark.asyncio
async def test_initialize_migrates_existing_scheduled_reminders_table(tmp_path: Path):
    db_path = tmp_path / "data" / "palli-local.sqlite3"
    db_path.parent.mkdir(parents=True, exist_ok=True)

    raw = sqlite3.connect(db_path)
    try:
        raw.execute(
            """
            CREATE TABLE scheduled_reminders (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER NOT NULL,
                platform TEXT NOT NULL,
                channel_id INTEGER NOT NULL,
                reminder_text TEXT NOT NULL,
                scheduled_time REAL NOT NULL,
                created_time REAL NOT NULL,
                is_completed BOOLEAN DEFAULT FALSE
            )
            """
        )
        raw.commit()
    finally:
        raw.close()

    brain = PalliBrain(str(db_path))
    await brain.initialize()
    await brain.close()

    inspect = sqlite3.connect(db_path)
    try:
        columns = {
            row[1]
            for row in inspect.execute("PRAGMA table_info('scheduled_reminders')").fetchall()
        }
        indexes = {
            row[1]
            for row in inspect.execute("PRAGMA index_list('scheduled_reminders')").fetchall()
        }
        version = inspect.execute("PRAGMA user_version").fetchone()[0]
    finally:
        inspect.close()

    assert {"runtime_job_id", "runtime_session_key", "surface_id", "kind"} <= columns
    assert "idx_scheduled_reminders_kind_due" in indexes
    # Batch 8, task 4 (ruling T4-1): an unversioned old-shape database runs
    # the ALTERs before the indexes once, then carries the newest version.
    from core.schema_migrations import MIGRATIONS

    assert version == MIGRATIONS[-1][0]
