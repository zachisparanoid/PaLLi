@pytest.mark.asyncio
async def test_deleting_sqlite_file_allows_fresh_restart(tmp_path: Path):
    db_path = tmp_path / "data" / "palli-local.sqlite3"

    first = PalliBrain(str(db_path))
    await first.initialize()
    try:
        user_id = await first.create_app_user(
            email="reset@test.local",
            password_hash=None,
            google_sub=None,
            role="admin",
        )
        assert int(user_id) == 1
        assert await first.get_app_user_by_email("reset@test.local") is not None
    finally:
        await first.close()

    if db_path.exists():
        db_path.unlink()
    for sidecar in _sqlite_sidecars(db_path):
        if sidecar.exists():
            sidecar.unlink()

    second = PalliBrain(str(db_path))
    await second.initialize()
    try:
        assert db_path.exists()
        assert await second.get_app_user_by_email("reset@test.local") is None
    finally:
        await second.close()


def test_adapt_sqlite_schema_statement_rewrites_postgres_features() -> None:
    statement = """
    CREATE TABLE demo (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        created_at DOUBLE PRECISION NOT NULL,
        payload JSONB,
        binary_data BYTEA,
        session_key TEXT DEFAULT metadata->>'session_key',
        settings JSONB NOT NULL DEFAULT '{}'::jsonb
    )
    """

    adapted = adapt_sqlite_schema_statement(statement)

    assert "INTEGER PRIMARY KEY AUTOINCREMENT" in adapted
    assert "created_at REAL NOT NULL" in adapted
    assert "payload TEXT" in adapted
    assert "binary_data BLOB" in adapted
    assert "json_extract(metadata, '$.session_key')" in adapted
    assert "::jsonb" not in adapted


@pytest.mark.asyncio
async def test_default_sqlite_bootstrap_program_initializes_schema_directly(tmp_path: Path):
    db_path = tmp_path / "data" / "palli-local.sqlite3"
    db_path.parent.mkdir(parents=True, exist_ok=True)

    brain = PalliBrain(str(db_path))
    conn = await brain._open_connection()
    try:
        await initialize_sqlite_schema(
            conn,
            program=DEFAULT_SQLITE_BOOTSTRAP_PROGRAM,
            logger=logging.getLogger(__name__),
        )
        table_name = await conn.fetchval(
            "SELECT name FROM sqlite_master WHERE type='table' AND name='users'"
        )
        kind_index = await conn.fetchval(
            "SELECT name FROM sqlite_master WHERE type='index' AND name='idx_scheduled_reminders_kind_due'"
        )
    finally:
        await conn.close()
        await brain.close()

    assert table_name == "users"
    assert kind_index == "idx_scheduled_reminders_kind_due"


