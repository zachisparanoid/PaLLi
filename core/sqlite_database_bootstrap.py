from __future__ import annotations

import logging
import os
import re
import sqlite3
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol, Sequence

import aiosqlite

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class SQLiteBootstrapProgram:
    ddl_statements: Sequence[str]
    migration_statements: Sequence[str]
    data_migration_statements: Sequence[str]
    index_statements: Sequence[str]
    scheduled_reminder_kind_statement: str
    scheduled_reminder_kind_index_statement: str


class SQLiteSchemaConnection(Protocol):
    def transaction(self) -> Any: ...

    async def execute(self, query: str, *args: Any) -> Any: ...

    async def fetchval(self, query: str, *args: Any) -> Any: ...


def adapt_sqlite_schema_statement(statement: str) -> str:
    sql = str(statement or "").strip()
    sql = re.sub(
        r"BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        "INTEGER PRIMARY KEY AUTOINCREMENT",
        sql,
        flags=re.IGNORECASE,
    )
    sql = re.sub(r"\bDOUBLE PRECISION\b", "REAL", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bJSONB\b", "TEXT", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bBYTEA\b", "BLOB", sql, flags=re.IGNORECASE)
    sql = re.sub(r"::[A-Za-z_][A-Za-z0-9_\[\]]*", "", sql)
    sql = re.sub(r"([A-Za-z_][A-Za-z0-9_]*)\s*->>\s*'([^']+)'", r"json_extract(\1, '$.\2')", sql)
    return sql


# 5000 -> 15000 (2026-08-09). WAL means readers never block, so this only
# governs how long HER writes wait on an external writer's transaction —
# in practice repair/backfill scripts holding the write lock for >5s. At 5s
# the losses were custody-grade: persist_turn (a user turn!), monologue
# indexing, sentiment writes all failed with "database is locked" in bursts
# on exactly the days scripts ran (08-01, 08-04, 08-06). A 15s-delayed write
# beats a lost one every time; nothing conversational waits on these writes.
SQLITE_BUSY_TIMEOUT_MS = 15000


async def configure_sqlite_connection(raw: aiosqlite.Connection) -> None:
    await _configure_sqlite_journal_mode(raw)
    await raw.execute("PRAGMA foreign_keys=ON")
    await raw.execute(f"PRAGMA busy_timeout={SQLITE_BUSY_TIMEOUT_MS}")
    await raw.commit()


async def _fetch_pragma_value(raw: aiosqlite.Connection, statement: str) -> str:
    cursor = await raw.execute(statement)
    try:
        row = await cursor.fetchone()
    finally:
        await cursor.close()
    return str((row or [""])[0] or "").strip().lower()


async def _configure_sqlite_journal_mode(raw: aiosqlite.Connection) -> None:
    try:
        applied_mode = await _fetch_pragma_value(raw, "PRAGMA journal_mode=WAL")
    except Exception as exc:
        logger.warning(
            "SQLite WAL mode unavailable; falling back to DELETE journal mode. (%s: %s)",
            type(exc).__name__,
            exc,
        )
        await _fetch_pragma_value(raw, "PRAGMA journal_mode=DELETE")
        return

    if applied_mode == "wal":
        return

    logger.warning(
        "SQLite requested WAL mode but SQLite kept %r; falling back to DELETE journal mode.",
        applied_mode or "unknown",
    )
    await _fetch_pragma_value(raw, "PRAGMA journal_mode=DELETE")


def inspect_sqlite_database_path(path: Path) -> dict[str, Any]:
    absolute_path = Path(path)
    parent = absolute_path.parent
    target_exists = absolute_path.exists()
    target_kind = "missing"
    if target_exists:
        target_kind = "directory" if absolute_path.is_dir() else "file"

    details: dict[str, Any] = {
        "absolute_path": str(absolute_path),
        "parent_path": str(parent),
        "target_exists": target_exists,
        "target_kind": target_kind,
        "target_writable": False,
        "parent_writable": False,
        "openable": False,
        "writable": False,
        "journal_mode_requested": "wal",
        "journal_mode_effective": "",
        "journal_mode_fallback_active": False,
        "journal_mode_warning": "",
        "error": "",
        "summary": "",
    }

    if target_kind == "directory":
        details["error"] = f"DATABASE_PATH points to a directory: {absolute_path}"
        details["summary"] = "Database path points to a directory."
        return details

    try:
        parent.mkdir(parents=True, exist_ok=True)
    except Exception as exc:
        details["error"] = f"{type(exc).__name__}: {exc}"
        details["summary"] = "Database parent directory could not be prepared."
        return details

    details["parent_writable"] = os.access(parent, os.W_OK)
    if not details["parent_writable"]:
        details["error"] = f"Database parent directory is not writable: {parent}"
        details["summary"] = "Database parent directory is not writable."
        return details

    details["target_writable"] = details["parent_writable"]
    if target_exists:
        details["target_writable"] = os.access(absolute_path, os.W_OK)
        if not details["target_writable"]:
            details["error"] = f"Existing database file is not writable: {absolute_path}"
            details["summary"] = "Existing database file is not writable."
            return details
        try:
            with sqlite3.connect(str(absolute_path), timeout=1.0) as raw:
                raw.execute("PRAGMA schema_version").fetchone()
        except Exception as exc:
            details["error"] = f"{type(exc).__name__}: {exc}"
            details["summary"] = "Existing database file could not be opened."
            return details

    probe_path: Path | None = None
    try:
        probe_fd, probe_name = tempfile.mkstemp(
            prefix=".palli-sqlite-probe-",
            suffix=".sqlite3",
            dir=parent,
        )
        os.close(probe_fd)
        probe_path = Path(probe_name)

        with sqlite3.connect(str(probe_path), timeout=1.0) as raw:
            journal_info = _configure_sqlite_journal_mode_sync(raw, log_warnings=False)
            raw.execute("PRAGMA foreign_keys=ON")
            raw.execute("PRAGMA busy_timeout=5000")
            raw.commit()
    except Exception as exc:
        details["error"] = f"{type(exc).__name__}: {exc}"
        details["summary"] = "SQLite could not open or configure a database in the target directory."
        return details
    finally:
        if probe_path is not None:
            _cleanup_sqlite_probe_path(probe_path)

    details["openable"] = True
    details["writable"] = True
    details["journal_mode_effective"] = str(journal_info.get("effective_mode") or "")
    details["journal_mode_fallback_active"] = bool(journal_info.get("fallback_active"))
    details["summary"] = "Database path is writable."
    if details["journal_mode_fallback_active"]:
        details["journal_mode_warning"] = (
            "SQLite WAL mode is unavailable for the configured database filesystem; "
            "runtime will use DELETE journal mode."
        )
    return details


def _configure_sqlite_journal_mode_sync(
    raw: sqlite3.Connection,
    *,
    log_warnings: bool = True,
) -> dict[str, Any]:
    try:
        applied_mode = _fetch_sync_pragma_value(raw, "PRAGMA journal_mode=WAL")
    except Exception as exc:
        if log_warnings:
            logger.warning(
                "SQLite WAL mode unavailable; falling back to DELETE journal mode. (%s: %s)",
                type(exc).__name__,
                exc,
            )
        delete_mode = _fetch_sync_pragma_value(raw, "PRAGMA journal_mode=DELETE")
        return {
            "effective_mode": delete_mode or "delete",
            "fallback_active": True,
        }

    if applied_mode == "wal":
        return {
            "effective_mode": "wal",
            "fallback_active": False,
        }

    if log_warnings:
        logger.warning(
            "SQLite requested WAL mode but SQLite kept %r; falling back to DELETE journal mode.",
            applied_mode or "unknown",
        )
    delete_mode = _fetch_sync_pragma_value(raw, "PRAGMA journal_mode=DELETE")
    return {
        "effective_mode": delete_mode or "delete",
        "fallback_active": True,
    }


def _fetch_sync_pragma_value(raw: sqlite3.Connection, statement: str) -> str:
    row = raw.execute(statement).fetchone()
    return str((row or [""])[0] or "").strip().lower()


def _cleanup_sqlite_probe_path(path: Path) -> None:
    candidates = [
        path,
        path.with_name(f"{path.name}-wal"),
        path.with_name(f"{path.name}-shm"),
        path.with_name(f"{path.name}-journal"),
    ]
    for candidate in candidates:
        try:
            candidate.unlink()
        except FileNotFoundError:
            continue
        except Exception:
            continue


# Skew threshold for the startup sweep. Probes from concurrent processes that
# are still in flight will have mtimes within seconds of "now"; only files
# older than this are considered safely strandable.
_SQLITE_PROBE_STALE_AGE_SECONDS = 300.0
_SQLITE_PROBE_GLOB = ".palli-sqlite-probe-*.sqlite3*"


def _sweep_stale_sqlite_probes(data_dir: Path) -> int:
    """Remove ``.palli-sqlite-probe-*.sqlite3*`` files older than the skew window.

    History: ``inspect_sqlite_database_path()`` opens a probe via
    ``tempfile.mkstemp(prefix=".palli-sqlite-probe-", suffix=".sqlite3", ...)``
    to confirm the data directory accepts a SQLite open + WAL configure. The
    cleanup-on-close path swallows exceptions so it can't crash bootstrap, but
    on Windows that silently strands the probe + WAL/SHM/journal sidecars when
    the WAL handle hasn't been released yet. Over hundreds of bootstraps the
    accumulated detritus grew to 806 files in the data directory.

    This sweep runs once during bootstrap, finds any matching files older than
    the skew window (so concurrent active probes from another process aren't
    wiped), and unlinks them. Returns the count actually removed for logging.
    Failures during unlink are tolerated per-file so one locked sidecar can't
    block cleanup of the rest.
    """
    if not data_dir.exists():
        return 0

    cutoff = time.time() - _SQLITE_PROBE_STALE_AGE_SECONDS
    removed = 0
    try:
        candidates = list(data_dir.glob(_SQLITE_PROBE_GLOB))
    except OSError:
        return 0

    for candidate in candidates:
        try:
            mtime = candidate.stat().st_mtime
        except FileNotFoundError:
            continue
        except OSError:
            continue
        if mtime > cutoff:
            continue
        try:
            candidate.unlink()
        except FileNotFoundError:
            continue
        except Exception:
            continue
        removed += 1

    return removed


# NOTE: core.schema_migrations.ensure_schema_sync mirrors this orchestration
# synchronously. Keep the phase order in sync.
async def initialize_sqlite_schema(
    conn: SQLiteSchemaConnection,
    *,
    program: SQLiteBootstrapProgram,
    logger: logging.Logger,
) -> int:
    """Bring the database's schema to the newest version and return it.

    Batch 8, task 4 (core/schema_migrations.py tells the whole story): a
    version-0 database runs today's program once (CREATEs, ALTERs, backfills,
    indexes, the reminders kind column and its index) before it is stamped; a
    stamped one runs the CREATEs, the numbered migrations it has not had and
    the indexes, never an ALTER. The version is read and written inside this
    one BEGIN IMMEDIATE, so a second process waits, then finds the work done.
    """
    # Lazy: core.schema_migrations imports the catalog, which imports this module.
    from core import schema_migrations

    async with conn.transaction():
        start = await schema_migrations.current_version_async(conn)
        if start == 0:
            await _run_unversioned_program(conn, program=program, logger=logger)
        else:
            await _run_required_statements(
                conn,
                program.ddl_statements,
                failure_prefix="Schema DDL failed",
                logger=logger,
            )
        version = await schema_migrations.migrate_async(conn, log=logger)
        if start != 0:
            await _run_required_statements(
                conn,
                (*program.index_statements, program.scheduled_reminder_kind_index_statement),
                failure_prefix="Schema index failed",
                logger=logger,
            )
    if version != start:
        logger.info("Database schema version %s -> %s", start, version)
    return version


async def _run_unversioned_program(
    conn: SQLiteSchemaConnection,
    *,
    program: SQLiteBootstrapProgram,
    logger: logging.Logger,
) -> None:
    """Today's whole program, unchanged and in today's order (version 0 only)."""
    await _run_required_statements(
        conn,
        program.ddl_statements,
        failure_prefix="Schema DDL failed",
        logger=logger,
    )
    await _run_best_effort_statements(conn, program.migration_statements)
    await _run_best_effort_statements(conn, program.data_migration_statements)
    await _run_required_statements(
        conn,
        program.index_statements,
        failure_prefix="Schema index failed",
        logger=logger,
    )
    await _ensure_scheduled_reminder_kind_support(conn, program=program, logger=logger)


async def _run_required_statements(
    conn: SQLiteSchemaConnection,
    statements: Sequence[str],
    *,
    failure_prefix: str,
    logger: logging.Logger,
) -> None:
    for idx, statement in enumerate(statements, start=1):
        try:
            await conn.execute(adapt_sqlite_schema_statement(statement))
        except Exception as exc:
            logger.error("%s (statement #%s): %s", failure_prefix, idx, exc)
            raise


async def _run_best_effort_statements(
    conn: SQLiteSchemaConnection,
    statements: Sequence[str],
) -> None:
    for statement in statements:
        try:
            await conn.execute(adapt_sqlite_schema_statement(statement))
        except Exception:
            pass


async def _ensure_scheduled_reminder_kind_support(
    conn: SQLiteSchemaConnection,
    *,
    program: SQLiteBootstrapProgram,
    logger: logging.Logger,
) -> None:
    try:
        await conn.execute(adapt_sqlite_schema_statement(program.scheduled_reminder_kind_statement))
    except Exception:
        pass
    try:
        await conn.execute(adapt_sqlite_schema_statement(program.scheduled_reminder_kind_index_statement))
    except Exception as exc:
        logger.error("Schema scheduled_reminders kind index failed: %s", exc)
        raise
