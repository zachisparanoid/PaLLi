def ensure_catalog_schema_sync(conn: sqlite3.Connection) -> None:
    """Synchronous schema bootstrap for use in tests and one-off scripts.

    Since Batch 8, task 4 this is core.schema_migrations.ensure_schema_sync:
    the same versioned boot as the async path (a version-0 database runs
    today's whole program once and is stamped; a stamped one runs the
    CREATEs, its pending numbered migrations and the indexes, never an
    ALTER), in one BEGIN IMMEDIATE, committed at the end as before.

    Intended for tests and one-off scripts that operate on raw ``sqlite3``
    connections; production code goes through :class:`PalliBrain` and the
    async path.
    """
    # Lazy: core.schema_migrations imports this module.
    from core.schema_migrations import ensure_schema_sync

    ensure_schema_sync(conn, program=DEFAULT_SQLITE_BOOTSTRAP_PROGRAM)


