"""Boot-time singleton for the PaLLi settings service.

Call boot_settings() once during startup. After that,
settings_service.snapshot() is available everywhere.
"""

from __future__ import annotations

import asyncio
import logging
import os
import tempfile
from pathlib import Path

from core.settings_service import SettingsChanged, SettingsService

logger = logging.getLogger(__name__)

def _resolve_default_yaml_path() -> Path:
    """Which settings file this process boots from.

    data/palli.yaml unless PALLI_SETTINGS_PATH names another (stranger-proofing
    week 1, task 1). A stranger — and every test that must not go near the live
    file — needs a way to point the boot somewhere else without editing the repo.
    """
    override = os.environ.get("PALLI_SETTINGS_PATH", "").strip()
    if override:
        return Path(override).expanduser()
    return Path(__file__).resolve().parent.parent / "data" / "palli.yaml"


_DEFAULT_YAML_PATH = _resolve_default_yaml_path()
# The shipped config (step 28, generated by scripts/release/make_example_yaml.py).
# A fresh clone has no data/palli.yaml at all; seed_from_example() copies this into
# place on the first boot so a stranger starts from a working file instead of a
# "settings file not found" traceback.
_EXAMPLE_YAML_PATH = Path(__file__).resolve().parent.parent / "data" / "palli.example.yaml"

settings_service = SettingsService(yaml_path=_DEFAULT_YAML_PATH)

_booted = False


def seed_from_example(yaml_path: Path | None = None) -> bool:
    """First boot on a fresh clone: copy data/palli.example.yaml into place.

    Bytes, not a re-serialisation — the example's 443 comment lines ARE the
    documentation, and a round trip through the schema would drop every one of
    them. Three laws: never overwrite an existing config (his live file is the
    truth, always), stay silent when there is nothing to copy from (a missing
    example is not a boot failure — load() still raises its honest 'settings file
    not found'), and say so exactly once when it does copy.

    Returns True when a file was written.
    """
    target = Path(yaml_path) if yaml_path is not None else _DEFAULT_YAML_PATH
    example = _EXAMPLE_YAML_PATH
    if target.exists() or not example.is_file():
        return False
    parent = target.parent
    parent.mkdir(parents=True, exist_ok=True)
    _atomic_copy(example, target, parent)
    logger.info(
        "No settings file at %s — seeded it from %s. Edit it; this happens once.",
        target, example,
    )
    return True


def _atomic_copy(example: Path, target: Path, parent: Path) -> None:
    """The write recipe from core/settings_service.py:139-158, for the same reason.

    A half-written config is WORSE than none: its existence suppresses the reseed
    above forever, and SettingsService.load() then fails with 'could not parse' on
    every boot after — on a stranger's first run, with nothing telling them that
    deleting the file fixes it. So the bytes land in a temp file in the target's own
    directory, are fsynced, and appear at the target in one atomic rename; a failure
    anywhere leaves the temp file removed and no config at all. os.replace also
    settles the two-boots-at-once race the exists() check alone cannot. 0o600 to
    match every later settings write.
    """
    fd = tempfile.NamedTemporaryFile(
        mode="wb", prefix=target.name + ".tmp.", dir=str(parent), delete=False,
    )
    tmp_path = Path(fd.name)
    try:
        fd.write(example.read_bytes())
        fd.flush()
        os.fsync(fd.fileno())
        fd.close()
        # Windows silently ignores 0o600 for some configs; suppress if unsupported.
        try:
            os.chmod(tmp_path, 0o600)
        except (NotImplementedError, PermissionError, OSError):
            pass
        os.replace(tmp_path, target)
    except Exception:
        try:
            fd.close()
        except Exception:
            pass
        tmp_path.unlink(missing_ok=True)
        raise


def boot_settings(*, yaml_path: Path | None = None) -> None:
    """Load and validate data/palli.yaml. Safe to call multiple times."""
    global _booted, settings_service
    if _booted:
        return
    if yaml_path is not None:
        settings_service = SettingsService(yaml_path=yaml_path)
    seed_from_example(settings_service._yaml_path)
    settings_service.load()
    settings_service.subscribe(_on_settings_changed)
    logger.info("Settings loaded from %s", settings_service._yaml_path)
    _booted = True


async def _rebuild_providers(event: SettingsChanged) -> None:
    """Rebuild provider registries from updated settings.

    Mirrors the pattern in core/plugin_runtime.py:864-868.
    Only rebuilds if the diff touches llm or voice sections.
    """
    try:
        from ai.llm_client import llm
        from ai.llm_provider_registry import build_default_provider_registry

        new_providers = build_default_provider_registry()
        await llm.replace_provider_registry(new_providers)
        logger.info("LLM provider registry rebuilt after settings change %s", event.change_id)
    except Exception:
        logger.exception("Failed to rebuild LLM providers after settings change %s", event.change_id)


def _on_settings_changed(event: SettingsChanged) -> None:
    """Synchronous listener that schedules the async provider rebuild."""
    try:
        loop = asyncio.get_running_loop()
        loop.create_task(_rebuild_providers(event))
    except RuntimeError:
        # No running event loop (e.g., in tests or CLI context)
        logger.debug("No event loop for provider rebuild; change will take effect on next request")
